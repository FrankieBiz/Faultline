import { NextRequest, NextResponse } from "next/server";

export const dynamic = "force-dynamic";
export const revalidate = 0;

type Context = { params: Promise<{ path: string[] }> };
const READ_PATH = /^(?:readiness|scenarios|jobs|jobs\/[\da-f-]+(?:\/events)?|artifacts\/[\da-f-]+)$/i;
const WRITE_PATH = /^(?:jobs|reset|revert|jobs\/[\da-f-]+\/(?:cancel|apply))$/i;

function isLoopbackOrPrivateHost(hostname: string): boolean {
  return (
    hostname === "localhost" ||
    hostname.endsWith(".localhost") ||
    hostname === "127.0.0.1" ||
    hostname.startsWith("127.") ||
    hostname === "[::1]" ||
    hostname === "::1" ||
    hostname === "0.0.0.0" ||
    hostname.endsWith(".local") ||
    hostname.endsWith(".lan") ||
    hostname.startsWith("192.168.") ||
    hostname.startsWith("10.") ||
    /^172\.(1[6-9]|2\d|3[01])\./.test(hostname)
  );
}

// Orca's local preview forwards a browser request to loopback and replaces the
// Host header. Fetch Metadata is generated by the browser, not page scripts;
// only a same-origin request from an Orca local preview can use this exception.
function isOrcaPreviewOrigin(origin: string, authority: string, site: string | null): boolean {
  if (site !== "same-origin") return false;
  try {
    const external = new URL(origin);
    const upstream = new URL(`http://${authority}`);
    return external.origin === origin && external.protocol === "http:"
      && external.hostname.endsWith(".orca.localhost")
      && ["127.0.0.1", "localhost"].includes(upstream.hostname);
  } catch {
    return false;
  }
}

// The Inspector is a loopback tool. Accepting any other Host would let a
// DNS-rebound page (for example evil.example resolving to 127.0.0.1) pass the
// same-origin check below and use the controller credential.
function isLocalHost(authority: string): boolean {
  try {
    const { hostname } = new URL(`http://${authority}`);
    return hostname === "127.0.0.1" || hostname === "localhost" || hostname.endsWith(".orca.localhost");
  } catch {
    return false;
  }
}

async function proxy(request: NextRequest, context: Context) {
  const { path } = await context.params;
  const target = path.join("/");
  if (!(request.method === "GET" ? READ_PATH : WRITE_PATH).test(target)) {
    return NextResponse.json({ error: { message: "Unknown controller route." } }, { status: 404 });
  }
  // Next's internal URL can use localhost even when the browser requested
  // 127.0.0.1. Host is the actual requested authority; do not trust forwarded hosts.
  const authority = request.headers.get("host") ?? request.nextUrl.host;
  if (!isLocalHost(authority)) {
    return NextResponse.json({ error: { message: "Open the Inspector through 127.0.0.1 or localhost." } }, { status: 403 });
  }
  // The controller credential stays server-side. Cross-site pages cannot use it
  // to submit jobs through this local UI, including form POSTs without CORS.
  if (request.method === "POST") {
    const origin = request.headers.get("origin");
    const expectedOrigin = `${request.nextUrl.protocol}//${authority}`;
    const site = request.headers.get("sec-fetch-site");
    let isAllowed = !origin || origin === expectedOrigin || isOrcaPreviewOrigin(origin, authority, site);
    if (!isAllowed && origin) {
      try {
        const originUrl = new URL(origin);
        const [authHost, authPort] = authority.split(":");
        const isLoopback = (h: string) => h === "localhost" || h === "127.0.0.1" || h.endsWith(".localhost");
        if (isLoopback(originUrl.hostname) && isLoopback(authHost) && (originUrl.port || "80") === (authPort || "80")) {
          isAllowed = true;
        }
      } catch {
        isAllowed = false;
      }
    }
    if (!isAllowed || site === "cross-site") {
      return NextResponse.json(
        { error: { code: "forbidden", message: "Same-origin request required." } },
        { status: 403 }
      );
    }
  }
  const token = process.env.FAULTLINE_CONTROL_TOKEN;
  if (!token) {
    return NextResponse.json({ error: { message: "Set FAULTLINE_CONTROL_TOKEN on the Inspector server." } }, { status: 503 });
  }
  const headers = new Headers({ Authorization: `Bearer ${token}` });
  for (const name of ["accept", "content-type", "last-event-id"]) {
    const value = request.headers.get(name);
    if (value) headers.set(name, value);
  }
  const base = process.env.FAULTLINE_ORCHESTRATOR_URL || "http://127.0.0.1:9000";
  try {
    const body = request.method === "POST" ? await request.text() : undefined;
    if (body && new TextEncoder().encode(body).length > 4096) {
      return NextResponse.json({ error: { message: "Request is too large." } }, { status: 413 });
    }
    const upstream = await fetch(`${base}/api/faultline/${target}${request.nextUrl.search}`, {
      method: request.method, headers, body, cache: "no-store", redirect: "error", signal: request.signal,
    });
    const responseHeaders = new Headers({ "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff" });
    for (const name of ["content-type", "content-disposition", "content-security-policy", "www-authenticate"]) {
      const value = upstream.headers.get(name);
      if (value) responseHeaders.set(name, value);
    }
    if (upstream.headers.get("content-type")?.includes("text/event-stream")) {
      responseHeaders.set("Cache-Control", "no-cache, no-transform");
      responseHeaders.set("X-Accel-Buffering", "no");
    }
    // Stream raw bytes: JSON decoding corrupts PNG/ZIP evidence and SSE errors.
    return new Response(upstream.body, { status: upstream.status, headers: responseHeaders });
  } catch {
    return NextResponse.json({ error: { message: "Controller unavailable. Start the demo stack and retry." } }, { status: 502 });
  }
}

export const GET = proxy;
export const POST = proxy;
